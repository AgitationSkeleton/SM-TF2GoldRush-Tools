#!/usr/bin/env python3
"""Write SourceMod gamedata for TF2: Gold Rush from SourceMod's own TF2 gamedata.

Gold Rush's x64 server.dll is TF2 code with one virtual fewer at TF2 vtable slot 13, so
every TF2 offset from slot 14 up is one lower (map_offsets.py aligns the CBaseEntity,
CTFPlayer and CTFWeaponBase vtables; AcceptInput is also confirmed by its string anchor:
TF2 38, Gold Rush 37). Non-vtable offsets (EntityListeners) are copied unchanged, and
signatures are left out (TF2's patterns do not match this binary).

  python -I gen_gamedata.py <sourcemod gamedata dir> <output gamedata dir>
Writes <out>/sdktools.games/custom/common.games.txt and <out>/sdkhooks.games/custom/common.games.txt
"""
import os
import re
import sys

SHIFT_FROM = 14
NON_VTABLE = {"EntityListeners"}
HEADER = ("/**\n * %s for TF2: Gold Rush (game folder tf_goldrush, x64).\n"
          " * Generated by SM-TF2GoldRush-Tools tools/gen_gamedata.py from SourceMod's TF2 gamedata\n"
          " * (%s): vtable offsets >= %d are one lower on Gold Rush. In custom/ so SM updates keep it.\n */\n")


def block(text, key):
    i = text.index('\t"%s"' % key)
    j = text.index("{", i)
    depth, k = 0, j
    while True:
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
            if depth == 0:
                return text[i:k + 1]
        k += 1


def shift_offsets(blk):
    out = []
    m = re.search(r'"Offsets"\s*\{', blk)
    head, rest = blk[:m.end()], blk[m.end():]
    depth, k = 1, 0
    while depth:
        depth += {"{": 1, "}": -1}.get(rest[k], 0)
        k += 1
    offsets, tail = rest[:k - 1], rest[k - 1:]

    def fix(mm):
        name, body = mm.group(1), mm.group(2)
        if name in NON_VTABLE:
            return mm.group(0)
        def num(nm):
            v = int(nm.group(2))
            return '%s"%d"' % (nm.group(1), v - 1 if v >= SHIFT_FROM else v)
        body = re.sub(r'("(?:windows|windows64|linux|linux64|mac)"\s*)"(\d+)"', num, body)
        return '"%s"%s' % (name, body)
    offsets = re.sub(r'"([^"]+)"(\s*\{[^{}]*\})', fix, offsets)
    blk = head + offsets + tail
    blk = re.sub(r'\n\t\t"Signatures"\s*\{.*?\n\t\t\}', "", blk, flags=re.S)
    return blk.replace('"tf"', '"tf_goldrush"', 1)


def main():
    src, out = sys.argv[1], sys.argv[2]
    jobs = [("sdktools.games/game.tf.txt", "SDKTools offsets", "sdktools.games/custom/common.games.txt"),
            ("sdkhooks.games/engine.ep2v.txt", "SDKHooks offsets", "sdkhooks.games/custom/common.games.txt")]
    for rel, what, dst in jobs:
        t = open(os.path.join(src, rel), encoding="utf-8").read()
        b = shift_offsets(block(t, "tf"))
        os.makedirs(os.path.dirname(os.path.join(out, dst)), exist_ok=True)
        open(os.path.join(out, dst), "w", encoding="utf-8", newline="\n").write(
            HEADER % (what, rel, SHIFT_FROM) + '"Games"\n{\n' + b + "\n}\n")
        print("wrote", dst)


if __name__ == "__main__":
    main()
